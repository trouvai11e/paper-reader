#!/usr/bin/env python3
"""Plan chunk line ranges from a MinerU markdown dump.

Section-first: top-level split points come from the level-2 headings in
tmp/headings.json (falling back to `## ` lines in the dump). Inside each
section, a greedy packer fills chunks up to an estimated-output cap
(`1.1 * text_lines + 3.5 * display_blocks`) and a hard line cap, preferring
blank-line and numbered-subsection boundaries and never cutting inside a
display-math block. A section whose heading denotes the bibliography is
emitted as `kind: "references"` chunks, generated by gen_references.py
instead of a translation subagent.

Writes tmp/chunk_manifest.json with status/next_line/counts fields for the
chunk state machine, plus `section` and `kind` per chunk.

Usage:
  uv run plan_chunks.py --mineru tmp/mineru_full.md --out tmp/chunk_manifest.json \
      --max-lines 300 --target-out 220 --headings tmp/headings.json
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

from readerlib import (
    NUM_HEAD_RE,
    is_references_heading,
    line_costs,
    math_mask,
)

MIN_SNAP = 20  # a preferred cut is used only when the chunk keeps this many lines


def estimate_out(lines: list[str], start: int, end: int) -> int:
    """Estimated reader output lines for [start, end] (1-based inclusive)."""
    return int(sum(line_costs(lines[start - 1:end])))


def split_section(lines: list[str], start: int, end: int,
                  max_lines: int, target_out: int) -> list[tuple[int, int]]:
    """Greedy split of [start, end] (1-based inclusive).

    Cuts prefer blank lines and numbered subsection headings, and never land
    inside a display-math block. A chunk always covers at least one line.
    """
    seg = lines[start - 1:end]
    costs = line_costs(seg)
    in_math = math_mask(seg)

    def allowed(idx: int) -> bool:
        """Whether the chunk may end at absolute line idx."""
        rel = idx - start
        if in_math[rel]:
            return False
        line = lines[idx - 1]
        return line.strip() == "" or bool(NUM_HEAD_RE.match(line))

    ranges: list[tuple[int, int]] = []
    cur = start
    while cur <= end:
        hard_end = min(end, cur + max_lines - 1)
        acc = 0.0
        best = cur
        for idx in range(cur, hard_end + 1):
            acc += costs[idx - start]
            if idx > cur and acc > target_out:
                break
            best = idx
        # Snap back to the last preferred boundary that keeps at least
        # MIN_SNAP lines (or half the chunk); otherwise cut at best itself,
        # which is still outside display math whenever possible.
        snap = None
        for idx in range(best, cur + MIN_SNAP - 1, -1):
            if idx > cur and allowed(idx):
                snap = idx
                break
        if snap is not None and snap - cur + 1 >= max(MIN_SNAP, (best - cur + 1) // 2):
            best = snap
        elif in_math[best - start]:
            for idx in range(best - 1, cur, -1):
                if not in_math[idx - start]:
                    best = idx
                    break
        ranges.append((cur, best))
        cur = best + 1
    return ranges


def page_map(lines: list[str]) -> dict[int, int]:
    pages: dict[int, int] = {}
    current = 0
    for i, line in enumerate(lines, 1):
        m = re.search(r"<!--\s*page\s+(\d+)", line)
        if m:
            current = int(m.group(1))
        pages[i] = current
    return pages


def section_bounds(lines: list[str], min_lines: int,
                   inventory: list[dict] | None = None) -> list[tuple[int, int, str]]:
    """Top-level section bounds as (start, end, title) triples.

    Split points come from level-2 headings in the heading inventory when it
    provides usable line numbers; otherwise from `## ` lines in the dump.
    """
    total = len(lines)
    titled: list[tuple[int, str]] = []
    if inventory:
        for h in inventory:
            try:
                line_no = int(h.get("line") or 0)
            except (TypeError, ValueError):
                continue
            level = int(h.get("level") or (str(h.get("num", "")).count(".") + 2))
            if level == 2 and 1 <= line_no <= total:
                title = h.get("en") or h.get("zh") or str(h.get("num") or "")
                titled.append((line_no, title))
    if not titled:
        titled = [(i, line[3:].strip())
                  for i, line in enumerate(lines, 1)
                  if re.match(r"^##\s+", line)]
    titled = sorted({s: t for s, t in titled}.items())
    starts = [1] + [s for s, _t in titled if s != 1]
    title_at = {s: t for s, t in titled}

    bounds: list[tuple[int, int, str]] = []
    for idx, s in enumerate(starts):
        e = starts[idx + 1] - 1 if idx + 1 < len(starts) else total
        if e >= s:
            bounds.append((s, e, title_at.get(s, "")))

    merged: list[tuple[int, int, str]] = []
    for s, e, t in bounds:
        # A references section stays standalone even when short: merging it
        # backward would unmark it, and merging it forward would send
        # bibliography lines to a translation subagent.
        if merged and (e - s + 1) < min_lines and not is_references_heading(t):
            ps, _pe, pt = merged[-1]
            merged[-1] = (ps, e, pt)
        else:
            merged.append((s, e, t))
    if (len(merged) > 1 and merged[0][1] - merged[0][0] + 1 < min_lines
            and not is_references_heading(merged[1][2])):
        s0, _e0, t0 = merged[0]
        merged[0] = (s0, merged[1][1], t0)
        del merged[1]
    return merged


def merge_small_ranges(ranges: list[tuple[int, int]], min_lines: int) -> list[tuple[int, int]]:
    merged: list[tuple[int, int]] = []
    for a, b in ranges:
        if merged and (b - a + 1) < min_lines:
            merged[-1] = (merged[-1][0], b)
        else:
            merged.append((a, b))
    if len(merged) > 1 and merged[0][1] - merged[0][0] + 1 < min_lines:
        merged[0] = (merged[0][0], merged[1][1])
        del merged[1]
    return merged


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--mineru", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--max-lines", type=int, default=300)
    ap.add_argument("--target-out", type=int, default=220)
    ap.add_argument("--min-lines", type=int, default=40)
    ap.add_argument("--headings")
    ap.add_argument("--prefix", default="c")
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args()

    out_path = Path(args.out)
    if out_path.exists() and not args.force:
        print(f"ERROR: {out_path} exists; use --force to replan", file=sys.stderr)
        return 1

    lines = Path(args.mineru).read_text(encoding="utf-8").splitlines()
    total = len(lines)
    if total == 0:
        print("ERROR: empty mineru file", file=sys.stderr)
        return 1
    pages = page_map(lines)

    inventory: list[dict] = []
    if args.headings and Path(args.headings).exists():
        inventory = json.loads(Path(args.headings).read_text(encoding="utf-8")).get("headings", [])

    chunks = []
    n = 0
    sections = section_bounds(lines, args.min_lines, inventory)
    for sec_idx, (sec_start, sec_end, sec_title) in enumerate(sections, 1):
        kind = "references" if is_references_heading(sec_title) else "translate"
        ranges = merge_small_ranges(
            split_section(lines, sec_start, sec_end, args.max_lines, args.target_out),
            args.min_lines)
        for a, b in ranges:
            n += 1
            hid = f"{args.prefix}{n:02d}"
            heads = [h["num"] for h in inventory
                     if h.get("line") and a <= int(h["line"]) <= b]
            eq = 0
            in_display = False
            for i in range(a, b + 1):
                if lines[i - 1].strip() == "$$":
                    if not in_display:
                        eq += 1
                    in_display = not in_display
                elif re.search(
                        r"\\begin\{(equation|align|aligned|gather|multline|cases|array"
                        r"|pmatrix|bmatrix)\}", lines[i - 1]):
                    eq += 1
            page_start, page_end = pages.get(a, 0), pages.get(b, 0)
            page_str = (f"{page_start}-{page_end}"
                        if page_start and page_end and page_start != page_end
                        else str(page_start or ""))
            chunks.append({
                "id": hid,
                "file": f"tmp/chunks/{hid}.md",
                "line_start": a,
                "line_end": b,
                "pages": page_str,
                "page_start": page_start,
                "page_end": page_end,
                "section": sec_idx,
                "section_title": sec_title,
                "kind": kind,
                "headings": heads,
                "est_out": estimate_out(lines, a, b),
                "density": round(eq * 100 / max(1, b - a + 1), 1),
                "status": "planned",
                "next_line": None,
                "counts": None,
            })

    manifest = {
        "total_lines": total,
        "max_lines": args.max_lines,
        "target_out": args.target_out,
        "chunks": chunks,
    }
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=1) + "\n",
                        encoding="utf-8")
    n_refs = sum(1 for c in chunks if c["kind"] == "references")
    print(f"wrote {out_path}: {len(chunks)} chunks ({n_refs} references), "
          f"{total} lines, target_out={args.target_out}")
    for c in chunks:
        tag = " [references]" if c["kind"] == "references" else ""
        print(f"  {c['id']}: {c['line_start']}-{c['line_end']} "
              f"({c['line_end'] - c['line_start'] + 1} lines, est_out={c['est_out']}, "
              f"eq/100={c['density']}) pages={c['pages']} section={c['section']}{tag}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
